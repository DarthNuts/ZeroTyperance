import { createHash } from "node:crypto";
export const WORKER_FILE = "sw.js";
export const CACHE_PREFIX = "zt-release-";
export interface OfflineCache {
    put(request: string, response: unknown): Promise<void>;
    match(request: string): Promise<unknown>;
}
export interface OfflineCaches {
    open(name: string): Promise<OfflineCache>;
    keys(): Promise<string[]>;
    delete(name: string): Promise<boolean>;
}
export interface OfflineEnv {
    caches: OfflineCaches;
    fetchFn: (request: unknown, init?: {
        cache: string;
    }) => Promise<{
        ok: boolean;
        status: number;
    }>;
    scope: string;
    precache: string[];
    cacheName: string;
    prefix: string;
}
export interface OfflineWorker {
    install(): Promise<void>;
    activate(): Promise<void>;
    keyOf(request: {
        url: string;
        method: string;
    }): string | null;
    respond(request: {
        url: string;
        method: string;
    }): Promise<unknown>;
}
export function createOfflineWorker(env: OfflineEnv): OfflineWorker {
    const listed = new Set(env.precache);
    const urlOf = (name: string): string => new URL(name, env.scope).href;
    return {
        async install() {
            await env.caches.delete(env.cacheName);
            const cache = await env.caches.open(env.cacheName);
            try {
                for (const name of env.precache) {
                    const r = await env.fetchFn(urlOf(name), { cache: "reload" });
                    if (!r.ok)
                        throw new Error(`${name}: status ${r.status}`);
                    await cache.put(urlOf(name), r);
                }
            }
            catch (e) {
                await env.caches.delete(env.cacheName);
                throw e;
            }
        },
        async activate() {
            for (const k of await env.caches.keys())
                if (k.startsWith(env.prefix) && k !== env.cacheName)
                    await env.caches.delete(k);
        },
        keyOf(request) {
            if (request.method !== "GET")
                return null;
            const u = new URL(request.url);
            const s = new URL(env.scope);
            if (u.origin !== s.origin || !u.pathname.startsWith(s.pathname))
                return null;
            let rel = decodeURIComponent(u.pathname.slice(s.pathname.length));
            if (rel === "")
                rel = "index.html";
            return listed.has(rel) ? rel : null;
        },
        async respond(request) {
            const key = this.keyOf(request);
            if (key !== null) {
                const hit = await (await env.caches.open(env.cacheName)).match(urlOf(key));
                if (hit)
                    return hit;
            }
            return env.fetchFn(request);
        },
    };
}
export interface NamedBytes {
    readonly name: string;
    readonly bytes: Uint8Array;
}
export function precacheList(names: readonly string[]): string[] {
    return [...new Set(names)].filter((n) => n !== WORKER_FILE).sort();
}
export function versionOf(files: readonly NamedBytes[]): string {
    const h = createHash("sha256");
    for (const f of [...files].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
        h.update(`${f.name}\0${f.bytes.length}\0`);
        h.update(f.bytes);
    }
    h.update(createOfflineWorker.toString());
    return h.digest("hex").slice(0, 16);
}
export function workerScript(files: readonly NamedBytes[], header = true): {
    text: string;
    cacheName: string;
    precache: string[];
} {
    const listedFiles = files.filter((f) => f.name !== WORKER_FILE);
    const precache = precacheList(listedFiles.map((f) => f.name));
    const cacheName = CACHE_PREFIX + versionOf(listedFiles);
    const text = [
        ...(header ? [`// ${WORKER_FILE} - generated by the site build (impl/release/offline.ts): the page's own files, cached whole per version.`] : []),
        `const PRECACHE = ${JSON.stringify(precache)};`,
        `const CACHE_NAME = ${JSON.stringify(cacheName)};`,
        `const create = ${createOfflineWorker.toString()};`,
        `const worker = create({ caches, fetchFn: (r, i) => fetch(r, i), scope: self.registration.scope, precache: PRECACHE, cacheName: CACHE_NAME, prefix: ${JSON.stringify(CACHE_PREFIX)} });`,
        `self.addEventListener("install", (e) => e.waitUntil(worker.install()));`,
        `self.addEventListener("activate", (e) => e.waitUntil(worker.activate()));`,
        `self.addEventListener("fetch", (e) => { if (worker.keyOf(e.request) !== null) e.respondWith(worker.respond(e.request)); });`,
        `self.addEventListener("message", (e) => { if (e.data === "skipWaiting") self.skipWaiting(); });`,
        ``,
    ].join("\n");
    return { text, cacheName, precache };
}
